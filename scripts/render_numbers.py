"""Write the README's figures from ``analysis.json``.

Every number the README states is generated by this script into a marked block.
Nothing between the markers is edited by hand, so a figure in the prose cannot
drift away from the run that produced it -- and ``tests/test_readme.py`` fails
if the block ever stops matching the artefact.
"""

from __future__ import annotations

import json
from typing import Any

from src import paths

BEGIN = "<!-- BEGIN GENERATED: figures come from data/processed/analysis.json -->"
END = "<!-- END GENERATED -->"

COVERAGE_POINTS = ("0.5", "0.8", "0.9")
STRATEGY_NAMES = {"cvss": "CVSS base score", "epss": "EPSS", "random": "Random"}


def render(analysis: dict[str, Any]) -> str:
    """The whole generated block, markers included."""
    retro = analysis["retrospective"]
    strategies = retro["strategies"]
    cvss80 = strategies["cvss"]["effort_at"]["0.8"]
    epss80 = strategies["epss"]["effort_at"]["0.8"]

    lines = [
        BEGIN,
        "",
        f"> Ranking {retro['universe']:,} live CVEs by CVSS means patching "
        f"**{cvss80:,.0f}** of them to cover 80 % of what attackers actually exploit. "
        f"Ranking by EPSS gets there with **{epss80:,.0f}** — "
        f"**{cvss80 / epss80:.1f}× less work**.",
        "",
        "> Freeze the scores and measure only what was exploited *afterwards*, and most of "
        "that advantage disappears.",
        "",
        "### The comparison everyone quotes",
        "",
        f"CVEs that must be patched to cover a given share of the {retro['positives']:,} "
        "vulnerabilities CISA has confirmed exploited:",
        "",
        "| Ranked by | 50 % covered | 80 % covered | 90 % covered |",
        "|---|---:|---:|---:|",
    ]
    for key in ("cvss", "epss", "random"):
        effort = strategies[key]["effort_at"]
        cells = " | ".join(f"{effort[point]:,.0f}" for point in COVERAGE_POINTS)
        lines.append(f"| {STRATEGY_NAMES[key]} | {cells} |")

    budget = retro["budget"]
    lines += [
        "",
        f"Put the other way round: patching every one of the **{budget:,}** CVEs rated "
        f"CVSS ≥ 9.0 catches **{strategies['cvss']['coverage_at_budget']:.0%}** of what is "
        f"exploited. Spending that same effort on the top {budget:,} by EPSS catches "
        f"**{strategies['epss']['coverage_at_budget']:.0%}**.",
        "",
        "### The comparison done honestly",
        "",
        "EPSS is trained on exploitation signals and the KEV catalogue *is* the exploitation "
        "ground truth, so the table above scores a forecaster against data it has already "
        "seen. Below, EPSS is frozen at a past date, the universe is rewound to what existed "
        "then, and the only vulnerabilities that count are the ones CISA confirmed exploited "
        "**afterwards**:",
        "",
        "| Scores frozen at | Universe | Later exploited | Budget | CVSS caught | EPSS caught | "
        "EPSS 95 % CI | Effort to 80 % |",
        "|---|---:|---:|---:|---:|---:|---|---:|",
    ]
    for block in analysis["prospective"]:
        cvss = block["strategies"]["cvss"]
        epss = block["strategies"]["epss"]
        low, high = epss["coverage_ci95"]
        lines.append(
            f"| {block['cutoff']} | {block['universe']:,} | {block['positives']} | "
            f"{block['budget']:,} | {cvss['coverage_at_budget']:.0%} | "
            f"{epss['coverage_at_budget']:.0%} | {low:.0%}–{high:.0%} | "
            f"{block['effort_ratio']['0.8']:.1f}× |"
        )

    worst = max(block["effort_ratio"]["0.8"] for block in analysis["prospective"])
    best_head = max(
        block["strategies"]["epss"]["coverage_at_budget"]
        / block["strategies"]["cvss"]["coverage_at_budget"]
        for block in analysis["prospective"]
    )
    least_head = min(
        block["strategies"]["epss"]["coverage_at_budget"]
        / block["strategies"]["cvss"]["coverage_at_budget"]
        for block in analysis["prospective"]
    )
    lines += [
        "",
        "Two results, and both hold at **every** cutoff:",
        "",
        f"1. **EPSS really does win at the head of the queue.** Same budget, "
        f"{least_head:.1f}–{best_head:.1f}× the later-exploited vulnerabilities caught.",
        f"2. **The {cvss80 / epss80:.1f}× headline is mostly measurement artefact.** With frozen "
        f"scores, EPSS needs *more* work than CVSS to reach 80 % coverage — effort ratio at "
        f"most {worst:.1f}× — because its tail buries a real share of what later gets exploited.",
        "",
        "So the queue this dashboard ranks is neither: confirmed exploitation first, EPSS for "
        "the head of the list, and CVSS kept as the guard on the tail.",
        "",
        f"*Data: CISA KEV catalogue {analysis['kev_catalog_version']}, EPSS "
        f"{analysis['epss_score_date'][:10]} (model {analysis['epss_model_version']}), NVD via "
        "the fkie-cad mirror. Regenerate with `make data`.*",
        "",
        END,
    ]
    return "\n".join(lines)


def replace_block(readme: str, block: str) -> str:
    start = readme.index(BEGIN)
    end = readme.index(END) + len(END)
    return readme[:start] + block + readme[end:]


def main() -> None:
    analysis = json.loads(paths.ANALYSIS.read_text())
    readme = paths.ROOT / "README.md"
    readme.write_text(replace_block(readme.read_text(), render(analysis)))
    print(f"figures written into {readme.name}")


if __name__ == "__main__":
    main()
